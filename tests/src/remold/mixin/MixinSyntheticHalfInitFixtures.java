package remold.mixin;

import java.lang.reflect.Constructor;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;

import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldInsnNode;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;
import org.objectweb.asm.tree.TypeInsnNode;

/**
 * Fixtures for the <b>expansion</b> half of the synthetic-class redefine semantics (invariant C3):
 * the capture list grows and the old {@code <init>} is kept as a tombstone.
 *
 * <p><b>Why two committed shapes instead of generated bytecode</b>: the candidate under test must be
 * produced the way the production path produces it — {@link MixinSyntheticSchema#retainConstructors}
 * copies the old constructor <b>out of the loaded bytes</b>. If the retained constructor were
 * hand-assembled here, the suite would prove something about ASM instead of about the tombstone.
 * So both shapes are ordinary committed classes and the candidate is
 * {@code bytes(HalfInitNext) renamed to HalfInitOld + retainConstructors(old bytes)}.</p>
 *
 * <p><b>Shapes</b> (deliberately the mixin capture shape, {@code this$0} + {@code val$*}):</p>
 * <ul>
 *   <li>{@code HalfInitOld} — the loaded shape: {@code this$0:Object}, {@code val$a:Object}, one
 *       2-arg capture constructor, one body method {@code test()};</li>
 *   <li>{@code HalfInitNext} — the re-woven shape: the same two fields plus a <b>new reference</b>
 *       field {@code val$b:Object} and a new primitive {@code val$c:int}; its only constructor
 *       takes the grown capture list, and {@code test()} now reads {@code val$b}.</li>
 * </ul>
 *
 * <p>Neither class is nested inside a helper: the semantics half defines the candidate bytes in a
 * private loader under the old name, and a top-level class has no {@code NestHost}/{@code
 * InnerClasses} attributes that would point at a host living in another loader.</p>
 */
final class MixinSyntheticHalfInitFixtures {

	/** Internal name of the loaded (old) shape; the candidate must keep it. */
	static final String OLD_INTERNAL = "remold/mixin/HalfInitOld";

	/** Dotted name of the loaded (old) shape. */
	static final String OLD_DOTTED = "remold.mixin.HalfInitOld";

	/** The constructor the loaded class owns and the candidate must retain. */
	static final String OLD_CTOR_DESC = "(Ljava/lang/Object;Ljava/lang/Object;)V";

	/** The constructor the re-woven shape declares (grown capture list). */
	static final String GROWN_CTOR_DESC = "(Ljava/lang/Object;Ljava/lang/Object;Ljava/lang/Object;I)V";

	private MixinSyntheticHalfInitFixtures() {
	}


	/**
	 * Test-only copy of the old {@code <init>} union: the production path no longer retains constructors
	 * (a member-schema change is refused outright), but the C3 candidate still has to be built the way a
	 * union <b>would</b> have built it, so the half-migrated semantics can be measured on its bytes.
	 */
	static List<String> retainConstructors(ClassNode fresh, byte[] loadedBytes) {
		java.util.Set<String> present = new java.util.HashSet<>();
		for (MethodNode m : fresh.methods) {
			if ("<init>".equals(m.name)) {
				present.add(m.desc);
			}
		}
		List<String> retained = new ArrayList<>();
		if (loadedBytes == null) {
			return retained;
		}
		ClassNode loaded = new ClassNode();
		new org.objectweb.asm.ClassReader(loadedBytes).accept(loaded, 0);
		for (MethodNode m : loaded.methods) {
			if ("<init>".equals(m.name) && !present.contains(m.desc)) {
				fresh.methods.add(m);
				present.add(m.desc);
				retained.add(m.desc);
			}
		}
		return retained;
	}

	/** Bytes the JVM loaded for the old shape (what the baseline/premain recorder would hold). */
	static byte[] oldShapeBytes() {
		return MixinSyntheticGateFixtures.bytesOf(HalfInitOld.class);
	}

	/** The redefine candidate: grown shape, renamed to the loaded name, old {@code <init>} retained. */
	static Candidate expandedCandidate() {
		byte[] old = oldShapeBytes();
		ClassNode node = grownShapeNode();
		List<String> retained = retainConstructors(node, old);
		return new Candidate(serialize(node), MixinSyntheticSchema.nodeFields(node), constructorsOf(node),
			retained, fieldWritesOf(node, "<init>", OLD_CTOR_DESC));
	}

	/**
	 * The re-woven shape as a node, renamed to the loaded name and <b>without</b> the old
	 * constructor: exactly what {@code InnerClassGenerator.generate} hands the production path.
	 *
	 * <p>Keeping the retention out of this helper is what makes the wiring suite meaningful: the
	 * retained {@code <init>} must be appended by {@code MixinInnerClassHotSwap} reading the
	 * baseline, not by the fixture.</p>
	 */
	static ClassNode grownShapeNode() {
		ClassNode node = MixinSyntheticGateFixtures.nodeOf(HalfInitNext.class);
		String from = "remold/mixin/HalfInitNext";
		node.name = OLD_INTERNAL;
		int leftovers = renameOwners(node, from, OLD_INTERNAL);
		if (leftovers != 0) {
			throw new IllegalStateException("the renamed shape still references " + from + " in " + leftovers
				+ " instruction(s); a redefine cannot carry a self reference to a class that will not exist");
		}
		return node;
	}

	/**
	 * The <b>body-only</b> candidate: identical field table and identical 2-arg {@code <init>} as the
	 * loaded shape, only {@code test()} returns {@code v2:...} instead of {@code v1:...}.
	 *
	 * <p>This is the {@code fieldTableChanged == false} direction: whatever the heap looks like, the
	 * gate must let it through and a live instance must observe the new body.</p>
	 */
	static ClassNode bodyOnlyShapeNode() {
		ClassNode node = MixinSyntheticGateFixtures.nodeOf(HalfInitBody.class);
		String from = "remold/mixin/HalfInitBody";
		node.name = OLD_INTERNAL;
		int leftovers = renameOwners(node, from, OLD_INTERNAL);
		if (leftovers != 0) {
			throw new IllegalStateException("the renamed body-only shape still references " + from + " in "
				+ leftovers + " instruction(s)");
		}
		return node;
	}

	/** Bytes of the body-only candidate (already renamed to the loaded name). */
	static byte[] bodyOnlyCandidateBytes() {
		return serialize(bodyOnlyShapeNode());
	}

	/** One redefinition candidate plus the structural facts the cases assert. */
	record Candidate(byte[] bytes, List<String> fields, List<String> constructors, List<String> retained,
		List<String> writesOfRetainedConstructor) {
	}

	/** Body method of both shapes. */
	static final String BODY = "test";

	/** Body method that only reads the new primitive capture (observable without touching the null one). */
	static final String COUNT = "capturedCount";

	/**
	 * Defines the candidate bytes under the loaded class name in a private child-first loader.
	 *
	 * <p>This is how the post-redefine shape is exercised without an agent: a redefine replaces the
	 * class in place, and a fresh loader holding the same name is the only way to run the very same
	 * bytes in a unit-test JVM. Every other name still delegates to the test class loader.</p>
	 */
	static Class<?> loadInFreshLoader(byte[] candidateBytes) {
		ClassLoader parent = MixinSyntheticHalfInitFixtures.class.getClassLoader();
		String target = OLD_DOTTED;
		ClassLoader loader = new ClassLoader(parent) {
			@Override
			protected Class<?> loadClass(String name, boolean resolve) throws ClassNotFoundException {
				if (!target.equals(name)) {
					return super.loadClass(name, resolve);
				}
				Class<?> defined = findLoadedClass(name);
				if (defined == null) {
					defined = defineClass(name, candidateBytes, 0, candidateBytes.length);
				}
				if (resolve) {
					resolveClass(defined);
				}
				return defined;
			}
		};
		try {
			return loader.loadClass(target);
		} catch (ClassNotFoundException e) {
			throw new AssertionError("the candidate bytes must define under " + target, e);
		}
	}

	/** Instantiates through the requested constructor (reflection: the shape only exists at run time). */
	static Object newInstance(Class<?> type, Class<?>[] params, Object... args) {
		try {
			Constructor<?> ctor = type.getDeclaredConstructor(params);
			ctor.setAccessible(true);
			return ctor.newInstance(args);
		} catch (InvocationTargetException e) {
			throw new AssertionError("the constructor " + type.getName() + java.util.Arrays.toString(params)
				+ " threw: " + e.getCause(), e.getCause());
		} catch (ReflectiveOperationException e) {
			throw new AssertionError("cannot instantiate " + type.getName() + " via "
				+ java.util.Arrays.toString(params) + ": " + e, e);
		}
	}

	/** Invokes a no-arg body method and returns its value; an exception fails the calling assertion. */
	static Object call(Object target, String method) {
		try {
			Method m = target.getClass().getDeclaredMethod(method);
			m.setAccessible(true);
			return m.invoke(target);
		} catch (InvocationTargetException e) {
			throw new AssertionError(method + "() threw " + e.getCause() + "\nstack:\n" + stackOf(e.getCause()),
				e.getCause());
		} catch (ReflectiveOperationException e) {
			throw new AssertionError("cannot invoke " + method + "() on " + target.getClass().getName(), e);
		}
	}

	/** Invokes a no-arg body method and returns what it threw, or {@code null} when it returned. */
	static Throwable failureOf(Object target, String method) {
		try {
			Method m = target.getClass().getDeclaredMethod(method);
			m.setAccessible(true);
			m.invoke(target);
			return null;
		} catch (InvocationTargetException e) {
			return e.getCause();
		} catch (ReflectiveOperationException e) {
			throw new AssertionError("cannot invoke " + method + "() on " + target.getClass().getName(), e);
		}
	}

	/** Full stack text of a throwable, for assertion messages and summaries. */
	static String stackOf(Throwable t) {
		StringBuilder sb = new StringBuilder();
		sb.append(t.getClass().getName()).append(": ").append(t.getMessage());
		for (StackTraceElement frame : t.getStackTrace()) {
			sb.append("\n    at ").append(frame);
		}
		return sb.toString();
	}

	private static int renameOwners(ClassNode node, String from, String to) {
		for (MethodNode m : node.methods) {
			if (m.instructions == null) {
				continue;
			}
			for (AbstractInsnNode insn = m.instructions.getFirst(); insn != null; insn = insn.getNext()) {
				if (insn instanceof FieldInsnNode field) {
					if (from.equals(field.owner)) {
						field.owner = to;
					}
				} else if (insn instanceof MethodInsnNode call) {
					if (from.equals(call.owner)) {
						call.owner = to;
					}
				} else if (insn instanceof TypeInsnNode type && from.equals(type.desc)) {
					type.desc = to;
				}
			}
		}
		int leftovers = 0;
		for (MethodNode m : node.methods) {
			if (m.instructions == null) {
				continue;
			}
			for (AbstractInsnNode insn = m.instructions.getFirst(); insn != null; insn = insn.getNext()) {
				if (insn instanceof FieldInsnNode field && from.equals(field.owner)) {
					leftovers++;
				} else if (insn instanceof MethodInsnNode call && from.equals(call.owner)) {
					leftovers++;
				} else if (insn instanceof TypeInsnNode type && from.equals(type.desc)) {
					leftovers++;
				}
			}
		}
		return leftovers;
	}

	/** {@code PUTFIELD} field names of one method (owner must be the class itself — no inherited writes). */
	private static List<String> fieldWritesOf(ClassNode node, String methodName, String desc) {
		List<String> writes = new ArrayList<>();
		for (MethodNode m : node.methods) {
			if (!methodName.equals(m.name) || (desc != null && !desc.equals(m.desc))) {
				continue;
			}
			if (m.instructions == null) {
				continue;
			}
			for (AbstractInsnNode insn = m.instructions.getFirst(); insn != null; insn = insn.getNext()) {
				if (insn instanceof FieldInsnNode field
					&& insn.getOpcode() == org.objectweb.asm.Opcodes.PUTFIELD
					&& field.owner.equals(node.name)) {
					writes.add(field.name);
				}
			}
		}
		return writes;
	}

	private static List<String> constructorsOf(ClassNode node) {
		List<String> descs = new ArrayList<>();
		for (MethodNode m : node.methods) {
			if ("<init>".equals(m.name)) {
				descs.add(m.desc);
			}
		}
		return descs;
	}

	private static byte[] serialize(ClassNode node) {
		ClassWriter writer = new ClassWriter(0);
		node.accept(writer);
		return writer.toByteArray();
	}
}

/**
 * Loaded shape of the growth case: two captured members and one 2-arg capture constructor.
 *
 * <p>Deliberately the shape a Mixin-generated {@code <Target>$Anonymous$<hash>} has: one
 * constructor per capture list, and the body reads captured members only.</p>
 */
class HalfInitOld {
	Object this$0;
	Object val$a;

	HalfInitOld(Object this$0, Object val$a) {
		this.this$0 = this$0;
		this.val$a = val$a;
	}

	String test() {
		return "v1:" + this.val$a;
	}
}

/**
 * Re-woven shape of the growth case: the capture list grew by a reference member
 * ({@code val$b}) and a primitive one ({@code val$c}), and the body now reads {@code val$b}
 * unguarded — exactly what a re-weave that starts using a new capture compiles to.
 */
class HalfInitNext {
	Object this$0;
	Object val$a;
	Object val$b;
	int val$c;

	HalfInitNext(Object this$0, Object val$a, Object val$b, int val$c) {
		this.this$0 = this$0;
		this.val$a = val$a;
		this.val$b = val$b;
		this.val$c = val$c;
	}

	String test() {
		return "v2:" + this.val$b.toString() + ":" + this.val$c;
	}

	int capturedCount() {
		return this.val$c;
	}
}

/**
 * Body-only counterpart of {@link HalfInitOld}: same two capture fields, same 2-arg
 * {@code <init>}, only {@code test()} returns {@code v2:...}.
 *
 * <p>Used for the {@code fieldTableChanged == false} direction: the JVM can swap the body of a
 * loaded class in place, so a live instance must start returning the new value while keeping its
 * field values — the only case that is safe regardless of how many instances are alive.</p>
 */
class HalfInitBody {
	Object this$0;
	Object val$a;

	HalfInitBody(Object this$0, Object val$a) {
		this.this$0 = this$0;
		this.val$a = val$a;
	}

	String test() {
		return "v2:" + this.val$a;
	}
}
